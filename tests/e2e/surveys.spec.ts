import { expect, test } from "@playwright/test";

for (const width of [1280, 390, 320]) {
  test(`Umfragen: Konfiguration, geschütztes Formular und Auswertung bei ${width}px`, async ({ page, browser }) => {
    await page.setViewportSize({ width, height: 844 });
    const origin = "http://127.0.0.1:3100";
    expect((await page.request.post("/api/login", { headers: { origin }, data: { password: "browser-test-password" } })).ok()).toBe(true);
    await page.goto("/");
    await page.getByRole("button", { name: "Umfragen", exact: true }).click();
    await page.getByRole("button", { name: "Neue Umfrage" }).click();
    await page.getByLabel("Titel", { exact: true }).fill(`Trikots ${width}`);
    await page.getByLabel("Beschreibung und Zweck").fill("Testbestellung mit fiktiven Daten");
    await page.getByLabel("Platzhalter für Feld 1 (optional)", { exact: true }).fill("z. B. Emil");
    await page.getByRole("button", { name: "Entwurf erstellen" }).click();
    const generated = page.getByLabel("Generiertes Umfrage-Passwort");
    await expect(generated).toBeVisible();
    const password = await generated.inputValue();
    expect(password.length).toBe(32);
    const link = await page.getByLabel("Teilnahmelink").inputValue();
    const token = link.split("/").at(-1)!;
    await page.getByRole("button", { name: "Passwort gesichert, ausblenden" }).click();
    const parentContext = await browser.newContext({ viewport: { width, height: 844 }, locale: "de-DE" });
    const parent = await parentContext.newPage();
    try {
      await parent.goto(link);
      await expect(parent.getByRole("heading", { name: "Umfrage nicht verfügbar" })).toBeVisible();
      await expect(parent.getByRole("contentinfo")).toHaveText("Powered by heydot.de - HEYDOT Agency - Eltville am Rhein");
      await expect(parent.getByRole("contentinfo").getByRole("link", { name: "heydot.de" })).toHaveAttribute("href", "https://www.heydot.de");
      expect(await parent.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
      await page.getByRole("button", { name: "Umfrage öffnen", exact: true }).click();
      await expect(page.getByRole("status")).toContainText("Umfrage geöffnet");
      await parent.reload();
      await expect(parent.getByRole("contentinfo")).toHaveText("Powered by heydot.de - HEYDOT Agency - Eltville am Rhein");
      await parent.getByLabel("Umfrage-Passwort").fill("wrong");
      await parent.getByRole("button", { name: "Umfrage öffnen", exact: true }).click();
      await expect(parent.locator("[data-ui=error][role=alert]")).toContainText("nicht richtig");
      await parent.getByLabel("Umfrage-Passwort").fill(password);
      await parent.getByRole("button", { name: "Umfrage öffnen", exact: true }).click();
      await expect(parent.getByRole("heading", { name: `Trikots ${width}`, exact: true })).toBeVisible();
      await expect(parent.getByRole("contentinfo")).toHaveText("Powered by heydot.de - HEYDOT Agency - Eltville am Rhein");
      const first = parent.getByLabel("Vorname des Kindes (Pflichtfeld)", { exact: true });
      await expect(first).toHaveAttribute("placeholder", "z. B. Emil");
      await first.fill("Emil");
      await parent.getByLabel("Trikotgröße (Pflichtfeld)", { exact: true }).selectOption({ label: "128" });
      // Lose the response after the server commits; the retry must not create another record.
      await parent.route(`**/api/public-surveys/${token}/responses`, async (route) => {
        await route.fetch(); await route.abort();
      }, { times: 1 });
      await parent.getByRole("button", { name: "Eintrag absenden" }).click();
      await expect(parent.locator("[data-ui=error][role=alert]")).toBeVisible();
      await expect(first).toBeDisabled();
      await parent.getByRole("button", { name: "Eintrag absenden" }).click();
      await expect(parent.getByRole("status")).toContainText("Dein Eintrag wurde gespeichert");
      await parent.getByRole("button", { name: "Weiteren Eintrag erfassen" }).click();
      await first.fill("emil");
      await parent.getByLabel("Trikotgröße (Pflichtfeld)", { exact: true }).selectOption({ label: "140" });
      await parent.getByRole("button", { name: "Eintrag absenden" }).click();
      await expect(parent.getByRole("status")).toContainText("gespeichert");
      await page.getByRole("button", { name: "Aktualisieren", exact: true }).click();
      await expect(page.getByRole("heading", { name: "Auswertung · 2 Einträge" })).toBeVisible();
      await expect(page.locator("[data-ui=survey-duplicate]")).toHaveCount(2);
      const firstResponse = page.locator("[data-ui=survey-response]").first();
      await firstResponse.getByRole("button", { name: "Antwort bearbeiten" }).click();
      await firstResponse.getByLabel("Vorname des Kindes (Pflichtfeld)", { exact: true }).fill("Mila");
      await firstResponse.getByRole("button", { name: "Antwort speichern" }).click();
      await expect(page.getByRole("status")).toContainText("Antwort gespeichert");
      await expect(page.locator("[data-ui=survey-duplicate]")).toHaveCount(0);
      const download = page.waitForEvent("download");
      await page.getByRole("button", { name: "CSV exportieren" }).click();
      expect((await download).suggestedFilename()).toBe("umfrage.csv");
      await page.getByText("Umfrage bearbeiten", { exact: true }).click();
      await expect(page.getByLabel("Label für Feld 1", { exact: true })).toBeDisabled();
      await expect(page.getByLabel("Antworttyp für Feld 2")).toBeDisabled();
      await page.getByLabel("Gleiche Werte im ersten Feld", { exact: false }).uncheck();
      await page.getByRole("button", { name: "Änderungen speichern" }).click();
      await expect(page.getByRole("status")).toContainText("Umfrage gespeichert");
      await page.getByRole("button", { name: "Umfrage schließen", exact: true }).click();
      await expect(page.getByRole("status")).toContainText("Umfrage geschlossen");
      await parent.getByRole("button", { name: "Weiteren Eintrag erfassen" }).click();
      await first.fill("Ben");
      await parent.getByLabel("Trikotgröße (Pflichtfeld)", { exact: true }).selectOption({ label: "116" });
      await parent.getByRole("button", { name: "Eintrag absenden" }).click();
      await expect(parent.getByRole("heading", { name: "Umfrage nicht verfügbar" })).toBeVisible();
      await page.getByRole("button", { name: "Umfrage öffnen", exact: true }).click();
      await expect(page.getByRole("status")).toContainText("Umfrage geöffnet");
      await page.locator("summary").filter({ hasText: /^Passwort ersetzen$/ }).click();
      page.once("dialog", (dialog) => dialog.accept());
      await page.getByRole("button", { name: "Passwort ersetzen", exact: true }).click();
      await expect(generated).toBeVisible();
      await parent.reload();
      await expect(parent.getByLabel("Umfrage-Passwort")).toBeVisible();
      await parent.getByLabel("Umfrage-Passwort").fill(password);
      await parent.getByRole("button", { name: "Umfrage öffnen", exact: true }).click();
      await expect(parent.locator("[data-ui=error][role=alert]")).toContainText("nicht richtig");
      await parent.getByLabel("Umfrage-Passwort").fill(await generated.inputValue());
      await parent.getByRole("button", { name: "Umfrage öffnen", exact: true }).click();
      await expect(first).toBeVisible();
      await expect(parent.locator("body")).toHaveJSProperty("scrollWidth", width);
      await expect(parent.locator("html")).toHaveJSProperty("scrollWidth", width);
      await parent.screenshot({ path: `test-results/survey-parent-${width}.png` });
      await expect(page.locator("body")).toHaveJSProperty("scrollWidth", width);
      await expect(page.locator("html")).toHaveJSProperty("scrollWidth", width);
      await page.screenshot({ path: `test-results/survey-admin-${width}.png` });
      page.once("dialog", (dialog) => dialog.accept());
      await page.getByRole("button", { name: "Umfrage endgültig löschen" }).click();
      await expect(page.getByRole("status")).toContainText("Umfrage und Antworten gelöscht");
      await parent.reload();
      await expect(parent.getByRole("heading", { name: "Umfrage nicht verfügbar" })).toBeVisible();

      // The second configuration has no name or choice assumptions and both fields are optional.
      await page.getByRole("button", { name: "Neue Umfrage" }).click();
      await page.getByLabel("Titel", { exact: true }).fill(`Wünsche ${width}`);
      await page.getByLabel("Label für Feld 1", { exact: true }).fill("Mannschaft");
      await page.getByLabel("Feld 1 ist Pflicht", { exact: true }).uncheck();
      await page.getByLabel("Antworttyp für Feld 2").selectOption("text");
      await page.getByLabel("Label für Feld 2", { exact: true }).fill("Wunsch");
      await page.getByLabel("Platzhalter für Feld 2 (optional)", { exact: true }).fill("Dein Wunsch");
      await page.getByLabel("Feld 2 ist Pflicht", { exact: true }).uncheck();
      await page.getByLabel("Passwort festlegen", { exact: true }).selectOption("manual");
      await page.getByLabel("Neues Passwort (12–128 Zeichen)").fill("custom-survey-password");
      await page.getByRole("button", { name: "Entwurf erstellen" }).click();
      await expect(page.getByRole("status")).toContainText("Entwurf erstellt");
      const secondLink = await page.getByLabel("Teilnahmelink").inputValue();
      await page.getByRole("button", { name: "Umfrage öffnen", exact: true }).click();
      await expect(page.getByRole("status")).toContainText("Umfrage geöffnet");
      await parent.goto(secondLink);
      await parent.getByLabel("Umfrage-Passwort").fill("custom-survey-password");
      await parent.getByRole("button", { name: "Umfrage öffnen", exact: true }).click();
      await expect(parent.getByLabel("Wunsch (optional)", { exact: true })).toHaveAttribute("placeholder", "Dein Wunsch");
      await parent.getByRole("button", { name: "Eintrag absenden" }).click();
      await expect(parent.locator("[data-ui=error][role=alert]")).toContainText("mindestens ein Feld");
      await parent.getByLabel("Wunsch (optional)", { exact: true }).fill("Neue Bälle");
      await parent.getByRole("button", { name: "Eintrag absenden" }).click();
      await expect(parent.getByRole("status")).toContainText("gespeichert");
      await page.getByRole("button", { name: "Aktualisieren", exact: true }).click();
      await expect(page.getByRole("heading", { name: "Auswertung · 1 Einträge" })).toBeVisible();
      await expect(page.locator("[data-ui=survey-response]")).toContainText("Keine Angabe");
      await expect(page.locator("[data-ui=survey-counts]")).toHaveCount(0);
      page.once("dialog", (dialog) => dialog.accept());
      await page.getByRole("button", { name: "Antwort löschen", exact: true }).click();
      await expect(page.getByRole("status")).toContainText("Antwort gelöscht");
      page.once("dialog", (dialog) => dialog.accept());
      await page.getByRole("button", { name: "Umfrage endgültig löschen" }).click();
      await expect(page.getByRole("status")).toContainText("Umfrage und Antworten gelöscht");
    } finally { await parentContext.close(); }
  });
}
